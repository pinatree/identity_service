// Package db — слой доступа к базе данных.
//
// На текущем этапе здесь живут только сущности — структуры данных, которые
// соответствуют таблицам БД. Подключение к СУБД и хранилища появятся позже,
// поэтому сущности намеренно не зависят ни от конкретного драйвера, ни от
// ORM: это «чистые» модели, которые можно сериализовать в любую схему.
package db

import "time"

// User — пользователь системы (таблица users).
//
// Пароль в открытом виде не хранится нигде: в PasswordHash лежит только
// криптографический хеш, а сам пароль существует лишь в момент запроса
// (регистрация/вход). ID — автоинкрементный счётчик: в PostgreSQL это
// BIGSERIAL, значение присваивает база, приложение читает его через
// RETURNING id.
type User struct {
	// ID — числовой идентификатор пользователя (первичный ключ, BIGSERIAL).
	// Уникальность и монотонность гарантирует база данных.
	ID int64

	// Login — логин пользователя, уникальный в системе.
	Login string

	// PasswordHash — хеш пароля. Никогда не содержит пароль в открытом виде.
	PasswordHash string

	// CreatedAt — момент создания учётной записи.
	CreatedAt time.Time

	// UpdatedAt — момент последнего изменения записи (логин, пароль и т.п.).
	UpdatedAt time.Time
}

// Session — сессия пользователя (таблица sessions).
//
// В TokenHash хранится хеш токена, а не сам токен: даже при утечке данных
// из базы токены не становятся известны злоумышленнику. У сессии всегда
// есть срок действия (ExpiresAt), а RevokedAt — механизм «мягкого» отзыва:
// сессия перестаёт быть действительной либо по истечении срока, либо
// принудительно (выход пользователя, смена пароля, компрометация).
type Session struct {
	// ID — UUID сессии в виде строки (первичный ключ).
	ID string

	// UserID — ссылка на User.ID (BIGINT) — владелец сессии.
	UserID int64

	// TokenHash — хеш токена сессии (не сам токен).
	TokenHash string

	// RefreshTokenHash — хеш refresh-токена сессии (не сам токен).
	//
	// При входе выдаётся пара токенов: обычный (для авторизации запросов)
	// и refresh (для продления сессии без повторного ввода пароля).
	// В хранилище лежат только хеши обоих токенов, поэтому даже при утечке
	// данных сами токены остаются неизвестны злоумышленнику.
	RefreshTokenHash string

	// CreatedAt — момент создания сессии.
	CreatedAt time.Time

	// ExpiresAt — момент истечения срока действия. Всегда заполнен:
	// сессия без срока действия не создаётся.
	ExpiresAt time.Time

	// RevokedAt — момент отзыва сессии. nil = сессия активна;
	// не-nil = сессия отозвана и больше недействительна.
	RevokedAt *time.Time
}

// IsActive возвращает true, пока сессия не отозвана (RevokedAt == nil).
//
// Это проверка только «отозвана ли сессия»: истёкшая по сроку сессия
// (ExpiresAt в прошлом) тоже не должна использоваться, поэтому вызывающий
// код обязан сравнивать момент «сейчас» с ExpiresAt отдельно.
func (s *Session) IsActive() bool {
	return s.RevokedAt == nil
}
